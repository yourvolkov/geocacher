#define BMI160_I2C_ADDR (0x68u)
#define HAL_TIMEOUT_I2C    10u // 10ms

/* Register map */
#define CHIP_ID_ADDR	(0x00u)
#define ERR_REG_ADDR	(0x01u)
#define GYR_X_ADDR		(0x0Cu) /* 2 bytes data */
#define GYR_Y_ADDR		(0x0Eu) /* 2 bytes data */
#define GYR_Z_ADDR		(0x10u) /* 2 bytes data */
#define ACC_X_ADDR		(0x12u) /* 2 bytes data */
#define ACC_Y_ADDR		(0x14u) /* 2 bytes data */
#define ACC_Z_ADDR		(0x16u) /* 2 bytes data */
