void BMI160_Init(void){
	uint8_t data[2];
	data[0] = CHIP_ID_ADDR;
	uint8_t size = 0u;
	HAL_StatusTypeDef res = HAL_I2C_Master_Transmit(&hi2c2, BMI160_I2C_ADDR, data, 1u, HAL_TIMEOUT_I2C);
	res = HAL_I2C_Master_Receive(&hi2c2, BMI160_I2C_ADDR, data, 1u, HAL_TIMEOUT_I2C);
	if(res){
		size = 255;
	}
}

